# -*- coding: utf-8 -*-
"""提示词模板模块"""

REASONING_PROMPT = """
    【任务背景】
    你是一个虚假新闻检测专家。你的任务是根据【权威证据】来判断【新闻文本】的真实性。
    - 【新闻文本】是用户提交的待检测新闻内容
    - 【权威证据】是从权威渠道检索到的相关信息
    - 你的目标是根据【权威证据】来判断【新闻文本】描述的事件是否真实发生

    请按以下步骤分析新闻真伪：
    
    第一步：提取新闻核心事实（从【新闻文本】中提取）
    -从【新闻文本】中概括新闻的主要内容：时间、地点、人物、事件经过
    -只提取新闻原文描述的客观事实，不要添加主观判断
    -【重要】不要混入权威证据的内容，只概括新闻原文
    
    第二步：分析权威证据（分析【权威证据】的内容）
    -【权威证据】是检索到的官方信息，提取其中的关键信息：消息来源、报道的核心内容、对事件性质的定性
    -特别关注：这是证实了新闻事件，还是揭露新闻是虚构/编造的？

    
    第三步：核心事实对比与性质判断
    -对比【新闻文本】与【权威证据】的核心内容
    -关键判断：【权威证据】是在证实【新闻文本】的真实性，还是在揭露【新闻文本】是虚构/编造的？
    
    【真实新闻的判断标准】：
    【权威证据】证实了【新闻文本】中的事件真实发生。例如：警方通报确认案件属实、官方媒体报道事件经过。
    
    【虚假新闻的判断标准】：
    【权威证据】揭露【新闻文本】是虚构、编造的。例如：
    - 【权威证据】称新闻是"虚构事实"——说明新闻是编造的骗局
    - 【权威证据】称新闻是"诈骗""骗局"——说明新闻是假的，是诈骗手段
    - 【权威证据】称新闻是"剧本""炒作"——说明新闻是人为编造的，不是真实发生的
    - 【权威证据】辟谣称新闻是"不实信息"——说明新闻内容不真实
    - 【权威证据】称新闻是"谣言""捏造""编造"——说明新闻是虚假的
    示例：
    如果【权威证据】明确指出新闻内容是"谣言""捏造""虚构""编造""不实信息"等相关词汇，则该新闻应判断为【虚假】！

    【重要区分规则】：
    - 如果【权威证据】描述的是"存在争议""引发热议""被质疑"等，说明事件本身真实存在但存在争议，不是虚构，应判断为【真实】
    - 如果【权威证据】说的是"事件不存在""是编造的""是虚假的"，才判断为【虚假】
    - 版权纠纷、合同争议、言论争议等事件本身是真实发生的，不是虚构

    【一致性判断定义】：
    - 【一致】：【权威证据】证实【新闻文本】描述的事件真实发生，或与新闻描述相符
    - 【不一致】：【权威证据】揭示【新闻文本】描述的事件并未发生、与事实不符，两者相互矛盾
    - 注意：判断依据是【权威证据】是否支持【新闻文本】的事实主张，而不是两者是否讨论了同一个事件。只要【权威证据】说明事件"并未发生""不存在""系虚假/编造/虚构"，而【新闻文本】声称事件发生，就判定为【不一致】。

    【判断为"无法确定"的条件】：
    1. 未检索到相关权威证据
    2. 证据与新闻关联度太低，无法判断


    输入信息：
    【新闻文本】：{text}
    【权威证据】：{authority_summary}

    请严格按照以下格式输出，不要添加任何额外内容(全部用中文回答)：
    注意：【一致性判断】必须同时包含判定词和完整理由，只输出判定词（如"一致"）而不写理由的视为无效。
    【新闻核心事实】用一段话详细概括【新闻文本】的核心内容，包括：涉及的人物、发生的地点、事件的具体经过。不要混入权威证据的内容。
    【权威证据】用一段话详细描述【权威证据】的核心内容，包括：消息来源、报道的关键事实、对事件性质的定性（证实/辟谣/虚构）。
    【一致性判断】一致/不一致/无法确定。主要理由：分析【权威证据】与【新闻文本】的核心内容是否一致，说明是证实相符还是相互矛盾，并解释为什么得出这个判断。判定词后必须紧跟"主要理由："并写出完整的一句理由，禁止只输出判定词而省略理由。
    """

AUTHORITY_SUMMARY_PROMPT = """请基于以下提供的文本内容，用你自己的话详细概括权威证据的核心信息。

【重要要求】
- 必须用完整的一段话输出，不要分点列举
- 不要输出"标题：""时间：""地点："这样的列表格式
- 用连贯的段落描述消息来源、事件经过和性质定性

【内容要求】
1. 明确说明消息来源（如：上海警方通报、新华社报道等）
2. 详细概括事件的核心事实（时间、地点、人物、事件经过）
3. 明确指出对事件性质的定性（是证实事件真实发生，还是揭露事件为虚构/编造/诈骗）
4. 如果是揭露虚假，必须明确说明"事件是虚构/编造的""新闻内容是假的""这是诈骗/骗局"等

提供的文本内容：
{authoritative_text}

请用完整的一段话详细概括，不要分点列举。"""


def build_reasoning_prompt(text, authority_summary=""):
    """构建推理链提示词"""
    if not authority_summary:
        authority_summary = "（未检索到权威证据）"
    
    return REASONING_PROMPT.format(
        text=text,
        authority_summary=authority_summary,
    )


def build_authority_summary_prompt(authoritative_text):
    """构建权威概要生成提示词"""
    return AUTHORITY_SUMMARY_PROMPT.format(authoritative_text=authoritative_text)
